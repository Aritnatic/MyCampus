export const getUpcomingEvents = () => events.filter(e => e.status === 'upcoming').sort((a, b) => new Date(a.startDate) - new Date(b.startDate))
export const getFeaturedEvents = () => events.filter(e => e.featured && e.status === 'upcoming')
export const getCrossUniversityEvents = () => events.filter(e => e.visibility === 'cross-university' && e.status === 'upcoming')